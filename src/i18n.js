let locale = "en";
export function getLanguage() {
  return locale;
}
export function t(key, params = {}) {
  const text = messages[locale][key] ?? messages.en[key];
  if (text === undefined) throw new Error(`Unknown translation key: ${key}`);
  return text.replace(/\{(\w+)\}/g, (_, name) =>
    String(params[name] ?? `{${name}}`),
  );
}
export function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  for (const attribute of ["title", "aria-label", "placeholder"]) {
    root.querySelectorAll(`[data-i18n-${attribute}]`).forEach((element) => {
      element.setAttribute(
        attribute,
        t(element.getAttribute(`data-i18n-${attribute}`)),
      );
    });
  }
  document.documentElement.lang = locale;
  document
    .querySelector('meta[name="description"]')
    ?.setAttribute("content", t("description"));
}
export function setLanguage(value) {
  locale = Object.hasOwn(messages, value) ? value : "en";
  if (typeof document !== "undefined") applyTranslations();
}
